// Regenerate the dashboard index after changing a published curriculum.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const courseSource = read('site.js').match(/var COURSES = (\[[\s\S]*?\n  \]);/)[1];
const reader = read('ai-reader.js').replace(
  "  if (document.readyState === 'loading') {",
  "  window.dashboardTrack = readerTrack;\n  window.dashboardTitle = displayTopicTitle;\n  if (document.readyState === 'loading') {"
);
const categories = ['Browser automation', 'Programming', 'Programming', 'AI', 'Browser automation', 'Test frameworks', 'CI/CD', 'Test frameworks', 'API testing', 'Version control'];

const courses = JSON.parse(courseSource).map(({ title, url, summary, icon, aliases }, index) => {
  const html = read(url);
  const trackId = html.match(/data-ai-reader-track="([^"]+)"/)[1];
  const context = vm.createContext({ window: {}, document: { readyState: 'loading', addEventListener() {} } });
  for (const [, file] of html.matchAll(/<script src="((?:content\/[\w-]+|playwright-curriculum)\.js)(?:\?[^"]*)?"/g)) {
    vm.runInContext(read(file), context, { filename: file });
  }
  vm.runInContext(reader, context, { filename: 'ai-reader.js' });
  const track = context.window.dashboardTrack(trackId);
  const lessons = track.topics.map((lesson) => {
    const href = '/' + url + (track.hashNavigation ? '#' : '?topic=') + encodeURIComponent(lesson.id);
    return {
      id: lesson.id,
      title: context.window.dashboardTitle(lesson),
      url: href,
      review: !lesson.hideReview || [lesson.title, lesson.learningObjective, ...(lesson.blocks || []).map((block) => block.heading)].some((text) => /interview questions|practice exercises?|hands-on exercise/i.test(text || '')),
      ...(lesson.subsections?.length ? { sections: lesson.subsections.map((section) => context.window.dashboardTitle(section)) } : {})
    };
  });
  return { title, url: '/' + url, summary, icon, aliases, category: categories[index], trackId, lessons };
});
fs.writeFileSync(path.join(root, 'dashboard/course-index.js'),
  '// Generated by scripts/build-dashboard-index.cjs.\nwindow.TestNovaCourseIndex = [\n' +
  courses.map((course) => '  ' + JSON.stringify(course)).join(',\n') + '\n];\n');
